// Copy the shared demo fixtures into the front end for mock mode (spec §4.4).
// Next.js cannot import files outside frontend/, so `pnpm dev`, `build`, `typecheck` and `test`
// run this first. The output folder is git-ignored.
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const src = join(here, "..", "..", "backend", "tests", "fixtures", "demo_homes")
const out = join(here, "..", "src", "mocks", "fixtures")

rmSync(out, { recursive: true, force: true })
mkdirSync(out, { recursive: true })

const files = readdirSync(src)
  .filter((f) => f.endsWith(".json"))
  .sort()
for (const f of files) copyFileSync(join(src, f), join(out, f))

const lines = [
  "// Generated by `pnpm mocks:sync` from backend/tests/fixtures/demo_homes. Do not edit.",
  'import type { DemoFixture } from "@/mocks/types"',
  "",
  ...files.map((f, i) => `import f${i} from "./${f}"`),
  "",
  `export const fixtures = [${files.map((_, i) => `f${i}`).join(", ")}] as unknown as DemoFixture[]`,
  "",
]
writeFileSync(join(out, "index.ts"), lines.join("\n"))
console.log(`mocks:sync copied ${files.length} fixtures`)
