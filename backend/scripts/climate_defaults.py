"""Fill `app/adapters/climate_defaults.py` from real Open-Meteo calls (spec §5, N8 hand-off).

uv run python -m scripts.climate_defaults

One reference point per English region and Wales (a central city). The adapter falls back to
the nearest point's figures when Open-Meteo cannot answer. Re-run if the model or the
thresholds in CONTRACT §2 change.
"""

import asyncio
from datetime import date
from pathlib import Path

from app.adapters.climate import PeriodStats, fetch_period
from app.adapters.http import UpstreamUnavailable
from app.config import CLIMATE_BASELINE_YEARS, CLIMATE_FUTURE_YEARS, CLIMATE_MODEL

RETRIES = 6
RETRY_WAIT_S = 65  # Open-Meteo's free tier has a per-minute limit (429); wait it out

OUT = Path(__file__).resolve().parents[1] / "app" / "adapters" / "climate_defaults.py"

# (region, reference point, lat, lon)
POINTS = (
    ("North East", "Newcastle upon Tyne", 54.97, -1.61),
    ("North West", "Manchester", 53.48, -2.24),
    ("Yorkshire and The Humber", "Leeds", 53.80, -1.55),
    ("East Midlands", "Nottingham", 52.95, -1.15),
    ("West Midlands", "Birmingham", 52.49, -1.89),
    ("East of England", "Cambridge", 52.21, 0.12),
    ("London", "Westminster", 51.50, -0.13),
    ("South East", "Guildford", 51.24, -0.57),
    ("South West", "Exeter", 50.72, -3.53),
    ("Wales", "Llandrindod Wells", 52.24, -3.38),
)

HEADER = '''"""Regional climate defaults: the fallback when Open-Meteo cannot answer (spec §5).

GENERATED by `uv run python -m scripts.climate_defaults` on {today} from real calls
(model {model}, baseline {b0}-{b1}, future {f0}-{f1}, CONTRACT §2 statistics). Do not edit
by hand. One row per English region and Wales; the adapter uses the nearest reference point.
"""

from dataclasses import dataclass

from pydantic import BaseModel


class _Period(BaseModel):
    hot_days: float
    heavy_rain_days: float
    max_wind_kmh: float


@dataclass(frozen=True)
class RegionDefault:
    name: str
    place: str
    lat: float
    lon: float
    baseline: _Period
    future: _Period


def _p(hot_days: float, heavy_rain_days: float, max_wind_kmh: float) -> _Period:
    return _Period(hot_days=hot_days, heavy_rain_days=heavy_rain_days, max_wind_kmh=max_wind_kmh)


# fmt: off
REGIONAL_DEFAULTS: tuple[RegionDefault, ...] = (
'''


async def _fetch(lat: float, lon: float, years: tuple[int, int]) -> PeriodStats:
    for attempt in range(RETRIES):
        try:
            return await fetch_period(lat, lon, years)
        except UpstreamUnavailable:
            if attempt == RETRIES - 1:
                raise
            print(f"  Open-Meteo busy, waiting {RETRY_WAIT_S} s ...", flush=True)
            await asyncio.sleep(RETRY_WAIT_S)
    raise AssertionError("unreachable")


async def main() -> None:
    rows = []
    for name, place, lat, lon in POINTS:
        base = await _fetch(lat, lon, CLIMATE_BASELINE_YEARS)
        fut = await _fetch(lat, lon, CLIMATE_FUTURE_YEARS)
        print(f"{name:26} {base} | {fut}", flush=True)
        rows.append(
            f'    RegionDefault("{name}", "{place}", {lat}, {lon},\n'
            f"                  _p({base.hot_days}, {base.heavy_rain_days}, {base.max_wind_kmh}),"
            f" _p({fut.hot_days}, {fut.heavy_rain_days}, {fut.max_wind_kmh})),\n"
        )
    b0, b1 = CLIMATE_BASELINE_YEARS
    f0, f1 = CLIMATE_FUTURE_YEARS
    text = HEADER.format(today=date.today(), model=CLIMATE_MODEL, b0=b0, b1=b1, f0=f0, f1=f1)
    OUT.write_text(text + "".join(rows) + ")\n# fmt: on\n")
    print(f"Wrote {OUT.name}: {len(rows)} regions")


if __name__ == "__main__":
    asyncio.run(main())
